-- Los índices de deduplicación y unicidad deben ser válidos.
SELECT t.relname AS tabla,i.relname AS indice,x.indisunique,x.indisvalid,pg_get_indexdef(x.indexrelid) AS definicion
FROM pg_index x JOIN pg_class i ON i.oid=x.indexrelid JOIN pg_class t ON t.oid=x.indrelid
WHERE t.relnamespace='public'::regnamespace AND i.relname IN
 ('log_comandos_message_id_unique','persona_correo_lower_unique','usuarios_correo_lower_unique',
  'prospectos_correo_lower_unique');

-- Un índice parcial o compuesto no equivale a UNIQUE global de lower(correo).
SELECT 'persona.correo' AS contrato,
       CASE WHEN EXISTS (SELECT 1 FROM pg_index WHERE indrelid=to_regclass('public.persona')
          AND indisunique AND indisvalid AND indisready AND indpred IS NULL
          AND indnkeyatts=1 AND indnatts=1 AND pg_get_expr(indexprs,indrelid)='lower((correo)::text)')
       THEN 'CUMPLE' ELSE 'FALTA O NO EQUIVALE' END AS unicidad_global;

